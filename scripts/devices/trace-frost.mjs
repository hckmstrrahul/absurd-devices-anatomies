// Route Frost's copper as vectors.   node scripts/devices/trace-frost.mjs
// Runs web/src/frost/router.ts over the lands in web/src/frost/print.ts and writes web/src/frost/routed.ts.
import {createRequire} from 'node:module';
import {writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..'),at=p=>resolve(root,p);
const esbuild=createRequire(at('web/package.json'))('esbuild');
const built=await esbuild.build({entryPoints:[at('web/src/frost/router.ts')],bundle:true,format:'esm',write:false,logLevel:'silent'});
const file=at('shots/frost/.router.mjs');mkdirSync(dirname(file),{recursive:true});writeFileSync(file,built.outputFiles[0].text);
const {routeBoard}=await import(pathToFileURL(file).href+'?'+Date.now()),t0=Date.now(),r=routeBoard();
const rows=list=>list.map(t=>'['+t.join(',')+']').join(',\n');
writeFileSync(at('web/src/frost/routed.ts'),`// GENERATED by scripts/devices/trace-frost.mjs with web/src/frost/router.ts. Do not edit by hand; run the script again.
// Print units (0.1 mm, origin at the board's back-left corner). A trace is [width × 10, x, y, x, y, …]; VIAS is flat [x, y, …].
export const TRACES:number[][]=[
${rows(r.traces)}
];
export const BOTTOM:number[][]=[
${rows(r.bottom)}
];
export const VIAS:number[]=[${r.vias.join(',')}];
`);
console.log(`routed in ${Date.now()-t0} ms`,JSON.stringify(r.stats));
